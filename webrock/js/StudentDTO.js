class StudentDTO
{
constructor(rollNumber,name,gender)
{
this.rollNumber=rollNumber;
this.name=name;
this.gender=gender;
}
setRollNumber(rollNumber)
{
this.rollNumber=rollNumber;
}
getRollNumber()
{
return this.rollNumber;
}
setName(name)
{
this.name=name;
}
getName()
{
return this.name;
}
setGender(gender)
{
this.gender=gender;
}
getGender()
{
return this.gender;
}
}
